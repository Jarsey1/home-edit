type I18nValue = {
  locale: Locale;
  localeCode: string;
  setLocale: (locale: Locale) => void;
  t: (
    key: TranslationKey,
    vars?: Record<string, string | number>,
  ) => string;
  number: (value: number, options?: Intl.NumberFormatOptions) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function LanguageProvider({
  initialLocale = "en",
  children,
}: {
  initialLocale?: Locale;
  children: ReactNode;
}) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    document.documentElement.lang = next;
    document.cookie = `${LOCALE_COOKIE}=${next}; path=/; max-age=31536000; samesite=lax`;
  }, []);

  const value = useMemo<I18nValue>(() => {
    const localeCode = locale === "es" ? "es-US" : "en-US";
    const dictionary = locale === "es" ? es : en;

    const t = (
      key: TranslationKey,
      vars?: Record<string, string | number>,
    ) => {
      let text = dictionary[key] ?? en[key] ?? key;
      if (vars) {
        for (const [name, replacement] of Object.entries(vars)) {
          text = text
            .split(`{${name}}`)
            .join(String(replacement));
        }
      }
      return text;
    };

    const number = (
      input: number,
      options?: Intl.NumberFormatOptions,
    ) => new Intl.NumberFormat(localeCode, options).format(input);

    return { locale, localeCode, setLocale, t, number };
  }, [locale, setLocale]);

  return (
    <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within a LanguageProvider");
  }
  return context;
}
